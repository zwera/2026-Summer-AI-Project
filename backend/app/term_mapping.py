"""
Part 1: 실무 언어 <-> 법률 용어 자동 보정 딕셔너리.

현장 경찰관이 쓰는 표현을 표준 법률 용어로 매핑해 검색 질의를 보정한다.
완전한 사전은 아니며, LLM 질의 최적화 단계에서 참고 컨텍스트로도 함께 제공된다.
"""

TERM_MAPPING: dict[str, str] = {
    "난동": "소란",
    "행패": "위력",
    "주취자": "술에 취한 사람",
    "취객": "술에 취한 사람",
    "몸싸움": "폭행",
    "말싸움": "협박 또는 모욕",
    "잡아갔다": "체포하였다",
    "끌고갔다": "임의동행 또는 체포",
    "붙잡았다": "체포 또는 제지",
    "뒤졌다": "수색하였다",
    "압수했다": "압수하였다",
    "미성년자": "청소년",
    "술 팔았다": "청소년에게 주류를 판매하였다",
    "담배 팔았다": "청소년에게 담배를 판매하였다",
    "불법영업": "무허가 영업 또는 영업정지 위반",
    "위생불량": "식품위생법 위반",
    "신고 안 받아줬다": "직무유기 여부",
    "때렸다": "폭행",
    "밀쳤다": "폭행 또는 상해",
    "욕했다": "모욕 또는 공무집행방해",
    "저항했다": "공무집행방해",
    "도망갔다": "도주",
    "훈방": "즉결심판 유예 또는 훈방조치",
}


def normalize_query(text: str) -> str:
    """실무 표현이 포함된 문장에서 매칭되는 용어를 법률 용어로 보정한 문자열을 반환.

    원문은 유지한 채 뒤에 보정 힌트를 덧붙이는 방식으로, 검색 정확도를 높이면서도
    원 문맥을 잃지 않도록 한다.
    """
    matched: list[str] = []
    for colloquial, formal in TERM_MAPPING.items():
        if colloquial in text and formal not in text:
            matched.append(formal)
    if not matched:
        return text
    return f"{text} ({', '.join(matched)})"
